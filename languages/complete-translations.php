function complete_po_file($file, $translations) {
    $content = file_get_contents($file);
    
    foreach ($translations as $english => $translated) {
        // Escape special characters for regex
        $english_escaped = preg_quote($english, '/');
        
        // Find msgid with empty msgstr and replace
        $pattern = '/(msgid "' . $english_escaped . '"\nmsgstr ")")/';
        $replacement = 'msgid "' . $english . '"' . "\n" . 'msgstr "' . $translated . '"';
        
        $content = preg_replace($pattern, $replacement, $content);
    }
    
    file_put_contents($file, $content);
}

